-- Run in the Supabase SQL Editor. Idempotent schema; no destructive resets.
begin;
create table if not exists public.courses (
 id integer primary key check (id > 0),
 metadata jsonb not null,
 updated_at timestamptz not null default now()
);
create table if not exists public.learning (
 user_id uuid not null references auth.users(id) on delete cascade,
 course_id integer not null references public.courses(id) on delete cascade,
 saved boolean not null default false,
 status text not null default 'not-started' check (status in ('not-started','in-progress','completed')),
 updated_at timestamptz not null default now(),
 primary key (user_id,course_id)
);
create table if not exists public.course_resources (
 id bigint generated by default as identity primary key,
 course_id integer not null references public.courses(id) on delete cascade,
 title text not null check (length(title) between 1 and 200),
 body text not null,
 position integer not null default 0,
 unique(course_id,position)
);
create or replace function public.touch_learning_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists learning_updated_at on public.learning;
create trigger learning_updated_at before update on public.learning
for each row execute function public.touch_learning_updated_at();

alter table public.courses enable row level security;
alter table public.learning enable row level security;
alter table public.course_resources enable row level security;
revoke all on public.courses, public.learning, public.course_resources from anon, authenticated;
grant select on public.courses to anon, authenticated;
grant select, insert, update, delete on public.learning to authenticated;
grant select on public.course_resources to authenticated;

drop policy if exists "Catalog is readable" on public.courses;
create policy "Catalog is readable" on public.courses for select to anon, authenticated using (true);
drop policy if exists "Own learning select" on public.learning;
create policy "Own learning select" on public.learning for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Own learning insert" on public.learning;
create policy "Own learning insert" on public.learning for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Own learning update" on public.learning;
create policy "Own learning update" on public.learning for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Own learning delete" on public.learning;
create policy "Own learning delete" on public.learning for delete to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Members can read study resources" on public.course_resources;
create policy "Members can read study resources" on public.course_resources for select to authenticated using ((select auth.uid()) is not null);
commit;
